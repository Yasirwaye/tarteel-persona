// scripts/build-page-index.ts
// Run with: npx tsx scripts/build-page-index.ts
// Generates src/data/quran/metadata/pages.ts: the first verse of each of the
// 604 mushaf pages (+ its opening words) and each surah's opening words, for
// the memorization tracker (Chapter / Juz / Hizb lists).
//
// QURAN_JSON_DIR=<dir> reads simple.json from disk (an api.alquran.cloud
// "quran/quran-simple" response) instead of downloading it.

import fs from "node:fs/promises";
import path from "node:path";
import { normalizeArabic } from "../src/lib/arabicUtils";

const OUT_FILE = path.join(process.cwd(), "src", "data", "quran", "metadata", "pages.ts");
const BISMILLAH = "بسم الله الرحمن الرحيم";
// Same cut as the rub' index: whole words while within 23 letters (vowel marks not counted)
const OPENING_MAX_LETTERS = 23;
const DIACRITICS = /[ؐ-ًؚ-ٰٟۖ-ۭـ]/g;

type Ayah = { numberInSurah: number; text: string; page: number };
type QuranResponse = { data: { surahs: { number: number; ayahs: Ayah[] }[] } };

async function load(): Promise<QuranResponse> {
  const dir = process.env.QURAN_JSON_DIR;
  if (dir) return JSON.parse(await fs.readFile(path.join(dir, "simple.json"), "utf8"));
  const res = await fetch("https://api.alquran.cloud/v1/quran/quran-simple");
  if (!res.ok) throw new Error(`quran-simple: HTTP ${res.status}`);
  return res.json();
}

function verseText(surah: number, ayah: Ayah): string {
  let text = ayah.text.replace(/﻿/g, "").trim();
  // This edition prefixes each surah's first ayah with the Bismillah (except Al-Fatihah)
  if (surah !== 1 && ayah.numberInSurah === 1) {
    const words = text.split(/\s+/);
    if (normalizeArabic(words.slice(0, 4).join(" ")) === normalizeArabic(BISMILLAH)) text = words.slice(4).join(" ");
  }
  return text;
}

function opening(text: string): string {
  const words = text.split(/\s+/).filter((w) => w.replace(DIACRITICS, "").replace(/[^ء-ي]/g, "").length > 0);
  const kept: string[] = [];
  let letters = -1;
  for (const w of words) {
    const len = w.replace(DIACRITICS, "").length + 1;
    if (kept.length > 0 && letters + len > OPENING_MAX_LETTERS) break;
    kept.push(w);
    letters += len;
  }
  return kept.join(" ");
}

async function main() {
  const quran = await load();
  const pages: string[] = [];
  const surahOpenings: string[] = [];
  let lastPage = 0;
  for (const surah of quran.data.surahs) {
    surahOpenings.push(JSON.stringify(opening(verseText(surah.number, surah.ayahs[0]))));
    for (const ayah of surah.ayahs) {
      if (ayah.page === lastPage) continue;
      if (ayah.page !== lastPage + 1) throw new Error(`page gap before ${surah.number}:${ayah.numberInSurah}`);
      lastPage = ayah.page;
      pages.push(`  { surahId: ${surah.number}, ayah: ${ayah.numberInSurah}, opening: ${JSON.stringify(opening(verseText(surah.number, ayah)))} },`);
    }
  }
  if (pages.length !== 604) throw new Error(`expected 604 pages, got ${pages.length}`);
  const body = `// src/data/quran/metadata/pages.ts
// GENERATED by scripts/build-page-index.ts — do not edit by hand.

export interface PageStart {
  surahId: number;
  ayah: number;
  /** First words of the page's first verse (index style, without "...") */
  opening: string;
}

/** First verse of each mushaf page: PAGE_STARTS[0] is page 1 */
export const PAGE_STARTS: PageStart[] = [
${pages.join("\n")}
];

/** Opening words of each surah's first ayah: SURAH_OPENINGS[0] is Al-Fatihah */
export const SURAH_OPENINGS: string[] = [
  ${surahOpenings.join(",\n  ")},
];
`;
  await fs.writeFile(OUT_FILE, body, "utf8");
  console.log(`${pages.length} pages → ${path.relative(process.cwd(), OUT_FILE)} (${(body.length / 1024).toFixed(0)} KB)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
