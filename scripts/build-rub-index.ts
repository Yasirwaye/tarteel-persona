// scripts/build-rub-index.ts
// Run with: npx tsx scripts/build-rub-index.ts
// Generates src/data/quran/metadata/rubs.ts: where each of the 240 rub' al-hizb
// (quarter-hizb) starts — verse, mushaf page and the opening words — for the
// juz' index ("Parts") in the surah index sheet. Data from api.quran.com.

import fs from "node:fs/promises";
import path from "node:path";

const OUT_FILE = path.join(process.cwd(), "src", "data", "quran", "metadata", "rubs.ts");
// Opening words are cut like the Quran app's index: whole words while the
// line stays within 23 letters (vowel marks not counted)
const OPENING_MAX_LETTERS = 23;
const DIACRITICS = /[ؐ-ًؚ-ٰٟۖ-ۭـ]/g;

interface Verse { verse_key: string; page_number: number; text_imlaei: string }

async function rubStart(n: number): Promise<Verse> {
  const url = `https://api.quran.com/api/v4/verses/by_rub_el_hizb/${n}?per_page=1&fields=text_imlaei,page_number`;
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url);
    if (res.ok) return (await res.json()).verses[0];
    if (attempt >= 3) throw new Error(`rub ${n}: HTTP ${res.status}`);
    await new Promise((r) => setTimeout(r, 1000 * (attempt + 1)));
  }
}

function opening(text: string): string {
  const words = text.split(/\s+/).filter((w) => w.replace(DIACRITICS, "").length > 0);
  const kept: string[] = [];
  let letters = -1;
  for (const w of words) {
    const len = w.replace(DIACRITICS, "").length + 1;
    if (kept.length > 0 && letters + len > OPENING_MAX_LETTERS) break;
    kept.push(w);
    letters += len;
  }
  return kept.join(" ");
}

async function main() {
  const rubs: string[] = [];
  for (let start = 1; start <= 240; start += 12) {
    const batch = await Promise.all(Array.from({ length: 12 }, (_, i) => rubStart(start + i)));
    for (const v of batch) {
      const [surahId, ayah] = v.verse_key.split(":").map(Number);
      rubs.push(`  { surahId: ${surahId}, ayah: ${ayah}, page: ${v.page_number}, opening: ${JSON.stringify(opening(v.text_imlaei))} },`);
    }
  }
  const body = `// src/data/quran/metadata/rubs.ts
// GENERATED by scripts/build-rub-index.ts — do not edit by hand.
// The 240 rub' al-hizb (quarter-hizb) starts, in order: 8 per juz, 4 per hizb.

export interface RubStart {
  surahId: number;
  ayah: number;
  page: number;
  /** First words of the verse (index style, without the trailing "...") */
  opening: string;
}

export const RUB_STARTS: RubStart[] = [
${rubs.join("\n")}
];
`;
  await fs.writeFile(OUT_FILE, body, "utf8");
  console.log(`${rubs.length} rub' starts → ${path.relative(process.cwd(), OUT_FILE)} (${(body.length / 1024).toFixed(0)} KB)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
