// scripts/build-recitation-vocabulary.ts
// Run with: npx tsx scripts/build-recitation-vocabulary.ts
// Generates src/data/quran/recitationVocabulary.ts: every Quran word form,
// normalized for recitation matching, in Uthmani AND modern spelling (what a
// speech model writes). Re-run after changing normalizeRecitationWord.
//
// QURAN_JSON_DIR=<dir> reads uthmani.json / simple.json / clean.json from disk
// (api.alquran.cloud "quran" responses) instead of downloading them.

import fs from "node:fs/promises";
import path from "node:path";
import { splitQuranWords, tokenizeRecitation } from "../src/lib/arabicUtils";

const EDITIONS = {
  uthmani: "quran-uthmani",
  simple: "quran-simple",
  clean: "quran-simple-clean",
} as const;
const OUT_FILE = path.join(process.cwd(), "src", "data", "quran", "recitationVocabulary.ts");

type QuranResponse = { data: { surahs: { ayahs: { text: string }[] }[] } };

async function load(name: keyof typeof EDITIONS): Promise<QuranResponse> {
  const dir = process.env.QURAN_JSON_DIR;
  if (dir) return JSON.parse(await fs.readFile(path.join(dir, `${name}.json`), "utf8"));
  const res = await fetch(`https://api.alquran.cloud/v1/quran/${EDITIONS[name]}`);
  if (!res.ok) throw new Error(`${EDITIONS[name]}: HTTP ${res.status}`);
  return res.json();
}

async function main() {
  const words = new Set<string>();
  for (const name of Object.keys(EDITIONS) as (keyof typeof EDITIONS)[]) {
    const quran = await load(name);
    for (const surah of quran.data.surahs) {
      for (const ayah of surah.ayahs) {
        const forms = name === "uthmani"
          ? splitQuranWords(ayah.text).map((t) => t.normalized)
          : tokenizeRecitation(ayah.text);
        for (const w of forms) if (w) words.add(w);
      }
    }
  }
  const list = [...words].sort();
  const body = `// src/data/quran/recitationVocabulary.ts
// GENERATED by scripts/build-recitation-vocabulary.ts — do not edit by hand.
// ${list.length} Quran word forms normalized with normalizeRecitationWord
// (Uthmani + modern spelling). Loaded lazily by loadQuranVocabulary().

export const QURAN_WORDS =
  "${list.join(" ")}";
`;
  await fs.writeFile(OUT_FILE, body, "utf8");
  console.log(`${list.length} words → ${path.relative(process.cwd(), OUT_FILE)} (${(body.length / 1024).toFixed(0)} KB)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
