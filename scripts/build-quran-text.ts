// scripts/build-quran-text.ts
// Run with: npx tsx scripts/build-quran-text.ts
// Generates src/data/quran/quranText.ts: every ayah in simple (vowelled) script,
// one per line in mushaf order, for the "similar phrases / similar verses"
// search in the verse menu. Loaded lazily (dynamic import), so it works offline.
//
// QURAN_JSON_DIR=<dir> reads simple.json from disk (an api.alquran.cloud
// "quran/quran-simple" response) instead of downloading it.

import fs from "node:fs/promises";
import path from "node:path";
import { normalizeArabic } from "../src/lib/arabicUtils";

const OUT_FILE = path.join(process.cwd(), "src", "data", "quran", "quranText.ts");
const BISMILLAH = "بسم الله الرحمن الرحيم";

type QuranResponse = { data: { surahs: { number: number; ayahs: { numberInSurah: number; text: string }[] }[] } };

async function load(): Promise<QuranResponse> {
  const dir = process.env.QURAN_JSON_DIR;
  if (dir) return JSON.parse(await fs.readFile(path.join(dir, "simple.json"), "utf8"));
  const res = await fetch("https://api.alquran.cloud/v1/quran/quran-simple");
  if (!res.ok) throw new Error(`quran-simple: HTTP ${res.status}`);
  return res.json();
}

async function main() {
  const quran = await load();
  const lines: string[] = [];
  for (const surah of quran.data.surahs) {
    for (const ayah of surah.ayahs) {
      let text = ayah.text.replace(/﻿/g, "").trim();
      // This edition prefixes each surah's first ayah with the Bismillah (not part of the ayah, except in Al-Fatihah)
      if (surah.number !== 1 && ayah.numberInSurah === 1) {
        const words = text.split(/\s+/);
        if (normalizeArabic(words.slice(0, 4).join(" ")) === normalizeArabic(BISMILLAH)) text = words.slice(4).join(" ");
      }
      lines.push(text);
    }
  }
  if (lines.length !== 6236) throw new Error(`expected 6236 ayahs, got ${lines.length}`);
  const body = `// src/data/quran/quranText.ts
// GENERATED by scripts/build-quran-text.ts — do not edit by hand.
// ${lines.length} ayahs (simple script, vowelled), one per line in mushaf order.

export const QURAN_TEXT = ${JSON.stringify(lines.join("\n"))};
`;
  await fs.writeFile(OUT_FILE, body, "utf8");
  console.log(`${lines.length} ayahs → ${path.relative(process.cwd(), OUT_FILE)} (${(body.length / 1024).toFixed(0)} KB)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
